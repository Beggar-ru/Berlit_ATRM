# Shell setup for the Berlit ATRM checkout.
#
#   .\tools\dev-env.ps1 build          # build the mod
#   .\tools\dev-env.ps1 runClient      # dev client (Avaritia + MineTweaker on the classpath)
#   . .\tools\dev-env.ps1              # load helpers: gw build / gw runClient
#
# Toolchains are reused from a sibling BerlitMod checkout when this repository has no
# .tools directory of its own, because the JDKs and the local maven mirror are large.
# Everything machine-specific is generated under .gradle-home (gitignored).

param(
    [Parameter(ValueFromRemainingArguments = $true)]
    [string[]] $Task
)

$root = Split-Path -Parent $PSScriptRoot

function Find-ToolRoot {
    if ($env:ATRM_TOOLS -and (Test-Path (Join-Path $env:ATRM_TOOLS 'jdk-25\bin\java.exe'))) {
        return (Resolve-Path $env:ATRM_TOOLS).Path
    }
    if (Test-Path (Join-Path $root '.tools\jdk-25\bin\java.exe')) {
        return (Join-Path $root '.tools')
    }
    $sibling = Join-Path (Split-Path -Parent $root) 'BerlitMod\.tools'
    if (Test-Path (Join-Path $sibling 'jdk-25\bin\java.exe')) {
        return (Resolve-Path $sibling).Path
    }
    return $null
}

$toolRoot = Find-ToolRoot
if (-not $toolRoot) {
    Write-Error @'
No JDK toolchains found.
Put JDK 25/21/17/8 under .tools (see BerlitMod's tools/env/fetch_jdks.py), point
ATRM_TOOLS at an existing tool directory, or place this checkout next to BerlitMod.
'@
    exit 1
}

# --- JDKs ------------------------------------------------------------------
$jdk = Join-Path $toolRoot 'jdk-25'
$env:JAVA_HOME = $jdk
$env:PATH = "$jdk\bin;$env:PATH"

# --- Gradle home -----------------------------------------------------------
$gradleHome = Join-Path $root '.gradle-home'
foreach ($sub in @('', 'tmp', 'init.d')) {
    $dir = if ($sub) { Join-Path $gradleHome $sub } else { $gradleHome }
    if (-not (Test-Path $dir)) { New-Item -ItemType Directory -Force -Path $dir | Out-Null }
}
$env:GRADLE_USER_HOME = $gradleHome

$temp = Join-Path $gradleHome 'tmp'
$env:TMP = $temp
$env:TEMP = $temp

# --- Toolchain + sandbox settings -----------------------------------------
# These are absolute, machine-specific paths; generated once and left alone so
# local edits survive.
$envProps = Join-Path $gradleHome 'gradle.properties'
if (-not (Test-Path $envProps)) {
    $toolchains = @('jdk-25', 'jdk-21', 'jdk-17', 'jdk-8') |
        ForEach-Object { Join-Path $toolRoot $_ } |
        Where-Object { Test-Path (Join-Path $_ 'bin\java.exe') } |
        ForEach-Object { $_ -replace '\\', '/' }
    $tmpDir = $temp -replace '\\', '/'

    $lines = @(
        '# Generated by tools\dev-env.ps1 - machine-specific Gradle settings.'
        '# Delete this file to regenerate it; paths below are absolute.'
        ''
        '# The DSH file sandbox blocks Gradle native file watching.'
        'org.gradle.vfs.watch=false'
        'org.gradle.native=false'
        ''
        "org.gradle.jvmargs=-Xmx4G -Dfile.encoding=UTF-8"
        ''
        "org.gradle.java.installations.paths=$($toolchains -join ',')"
        'org.gradle.java.installations.auto-download=false'
        'org.gradle.java.installations.auto-detect=true'
        ''
        'systemProp.org.gradle.internal.http.connectionTimeout=15000'
        'systemProp.org.gradle.internal.http.socketTimeout=20000'
        ''
        'org.gradle.parallel=true'
        'org.gradle.caching=true'
        '# RFG Download cannot be serialized into the configuration cache.'
        'org.gradle.configuration-cache=false'
    )
    $utf8NoBom = New-Object System.Text.UTF8Encoding($false)
    [System.IO.File]::WriteAllText($envProps, ($lines -join "`r`n") + "`r`n", $utf8NoBom)
}

# --- Local maven mirror ----------------------------------------------------
# The GTNH Nexus does not deliver jar bodies on some networks; BerlitMod's
# tools/env/mirror.py pre-builds a maven repository with the missing jars.
$mirror = Join-Path $root '.tools\local-maven'
if (-not (Test-Path $mirror)) {
    $mirror = Join-Path $toolRoot 'local-maven'
}
if (Test-Path $mirror) {
    $mirrorPath = (Resolve-Path $mirror).Path -replace '\\', '/'
    $init = @"
// Generated by tools\dev-env.ps1 - puts the local jar mirror in front of the
// GTNH Nexus for settings plugins and project dependencies.
def mirrorUri = new File('$mirrorPath').toURI()

beforeSettings { settings ->
    settings.pluginManagement.repositories.maven { repo ->
        repo.name = 'ATRMLocalMirror'
        repo.url = mirrorUri
    }
}

settingsEvaluated { settings ->
    settings.dependencyResolutionManagement.repositories.maven { repo ->
        repo.name = 'ATRMLocalMirror'
        repo.url = mirrorUri
    }
}

allprojects { project ->
    project.repositories.maven { repo ->
        repo.name = 'ATRMLocalMirror'
        repo.url = mirrorUri
    }
}
"@
    $utf8NoBom = New-Object System.Text.UTF8Encoding($false)
    [System.IO.File]::WriteAllText(
        (Join-Path $gradleHome 'init.d\local-mirror.gradle'),
        ($init -replace "`r`n", "`n"),
        $utf8NoBom)
}

$gwPath = Join-Path $root 'gradlew.bat'

function Invoke-BerlitGradle {
    & $gwPath --no-watch-fs @args
}

if ($Task.Count -gt 0) {
    $gradleArgs = @(
        if ($Task[0] -in @('gw', 'gradlew', 'gradle')) {
            $Task | Select-Object -Skip 1
        } else { $Task }
    )
    if ($gradleArgs.Count -eq 0) {
        Write-Host 'Usage: .\tools\dev-env.ps1 <gradle task>, for example build'
        exit 0
    }
    & $gwPath --no-watch-fs @gradleArgs
    exit $LASTEXITCODE
}

if ($MyInvocation.InvocationName -ne '.') {
    Write-Host 'Usage:'
    Write-Host '  .\tools\dev-env.ps1 build'
    Write-Host '  .\tools\dev-env.ps1 runClient'
    Write-Host '  . .\tools\dev-env.ps1   # then: gw build'
    exit 0
}

Set-Item -Path Function:global:gw -Value ([scriptblock]::Create("& '$gwPath' --no-watch-fs @args"))
Write-Host "JAVA_HOME        = $env:JAVA_HOME"
Write-Host "GRADLE_USER_HOME = $env:GRADLE_USER_HOME"
Write-Host "tool root        = $toolRoot"
Write-Host "Ready: 'gw build', 'gw runClient'."
